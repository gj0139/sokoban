// Build the 20-level embed for sokoban.html from the Microban reference set,
// validating that every level is well-formed (1 player, boxes === goals).
import { readFile, writeFile } from 'node:fs/promises';

const src = await readFile(new URL('./ref-levels2.js', import.meta.url), 'utf8');
const m = src.match(/const LEVELS = \[([\s\S]*?)\n\];/);
if (!m) throw new Error('cannot find LEVELS array in ref-levels2.js');

const LEVELS = new Function(`return [${m[1]}];`)();
console.log(`reference set: ${LEVELS.length} levels`);

function check(text) {
  const rows = text.split('\n');
  const flat = rows.join('');
  const count = (re) => (flat.match(re) || []).length;
  return {
    players: count(/[@+]/g),   // @ player, + player standing on a goal
    boxes: count(/[$*]/g),     // $ box, * box resting on a goal
    goals: count(/[.*+]/g),    // . goal, * box-on-goal, + player-on-goal
    w: Math.max(...rows.map((r) => r.length)),
    h: rows.length,
  };
}

const picked = [];
const stats = { invalid: 0, players: 0, boxes: 0, big: 0 };
let maxW = 0, maxH = 0;
for (let i = 0; i < LEVELS.length; i++) {
  const lvl = LEVELS[i];
  const info = check(lvl);
  if (info.players !== 1) { stats.players++; console.warn(`  skip #${i + 1}: ${info.players} players`); continue; }
  if (info.boxes !== info.goals) { stats.boxes++; console.warn(`  skip #${i + 1}: ${info.boxes} boxes vs ${info.goals} goals`); continue; }
  if (info.w > 16 || info.h > 14) stats.big++;
  maxW = Math.max(maxW, info.w);
  maxH = Math.max(maxH, info.h);
  picked.push({ n: i + 1, lvl, info });
}

console.log(`picked ${picked.length} / ${LEVELS.length} levels  (skipped: ${stats.players} bad players, ${stats.boxes} box/goal mismatch)`);
console.log(`largest board: ${maxW} x ${maxH}, ${stats.big} levels wider/taller than 16x14`);
for (const p of picked) console.log(`  Microban #${String(p.n).padStart(3)}  ${p.info.w}x${p.info.h}  boxes=${p.info.boxes}`);

const body = picked.map((p) => {
  const rows = p.lvl.split('\n');
  return '  `' + rows.join('\n') + '`,';
}).join('\n');

const out = `// Auto-generated by tools/build-levels.mjs — Microban by David W. Skinner (2000), freely distributable with credit.
const LEVELS = [
${body.replace(/,\s*$/, ',')}
];
`;
await writeFile(new URL('./levels-embed.js', import.meta.url), out);
console.log(`\nwrote tools/levels-embed.js (${out.length} bytes)`);
